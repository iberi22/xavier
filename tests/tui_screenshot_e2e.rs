fn color_to_rgb(color: Color) -> Rgb<u8> {
    match color {
        Color::Reset => Rgb([200, 200, 200]),
        Color::Black => Rgb([0, 0, 0]),
        Color::Red => Rgb([255, 85, 85]),
        Color::Green => Rgb([85, 255, 85]),
        Color::Yellow => Rgb([255, 255, 85]),
        Color::Blue => Rgb([85, 85, 255]),
        Color::Magenta => Rgb([255, 85, 255]),
        Color::Cyan => Rgb([85, 255, 255]),
        Color::Gray => Rgb([170, 170, 170]),
        Color::DarkGray => Rgb([85, 85, 85]),
        Color::LightRed => Rgb([255, 170, 170]),
        Color::LightGreen => Rgb([170, 255, 170]),
        Color::LightYellow => Rgb([255, 255, 170]),
        Color::LightBlue => Rgb([170, 170, 255]),
        Color::LightMagenta => Rgb([255, 170, 255]),
        Color::LightCyan => Rgb([170, 255, 255]),
        Color::White => Rgb([255, 255, 255]),
        _ => Rgb([200, 200, 200]),
    }
}

fn render_buffer_to_png(buffer: &Buffer, output_path: &Path) {
    let width = buffer.area.width as u32;
    let height = buffer.area.height as u32;
    let mut img = RgbImage::new(width * FONT_WIDTH, height * FONT_HEIGHT);

    for y in 0..height {
        for x in 0..width {
            let cell = &buffer[(x as u16, y as u16)];
            let bg_color = color_to_rgb(cell.bg);
            let fg_color = color_to_rgb(cell.fg);

            // Draw background
            for py in 0..FONT_HEIGHT {
                for px in 0..FONT_WIDTH {
                    img.put_pixel(x * FONT_WIDTH + px, y * FONT_HEIGHT + py, bg_color);
                }
            }

            // Draw character
            let ch = cell.symbol().chars().next().unwrap_or(' ');
            let glyph_idx = if (ch as u32) >= 32 && (ch as u32) < 128 {
                (ch as u32 - 32) as usize
            } else {
                0
            };

            for py in 0..FONT_HEIGHT {
                let row = FONT[glyph_idx * 8 + py as usize];
                for px in 0..FONT_WIDTH {
                    if (row & (0x80 >> px)) != 0 {
                        img.put_pixel(x * FONT_WIDTH + px, y * FONT_HEIGHT + py, fg_color);
                    }
                }
            }
        }
    }

    img.save(output_path).expect("failed to save image");
}

async fn start_mock_server() -> String {
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    let port = listener.local_addr().unwrap().port();

    let app = Router::new()
        .route(
            "/v1/account/usage",
            get(|| async {
                Json(json!({
                    "document_count": 42,
                    "requests_used": 100,
                    "storage_bytes_used": 1024 * 1024,
                    "storage_bytes_limit": 1024 * 1024 * 100,
                    "provider_quotas": {
                        "openai": { "used_today": 500 }
                    }
                }))
            }),
        )
        .route(
            "/v1/memories",
            get(|| async {
                Json(json!({
                    "memories": [
                        {
                            "id": "mem_1",
                            "content": "Xavier is an AI memory system.",
                            "path": "docs/intro.md",
                            "metadata": {}
                        }
                    ]
                }))
            }),
        )
        .route(
            "/panel/api/threads",
            get(|| async {
                Json(json!([
                    {
                        "id": "thread_1",
                        "title": "Initial Setup"
                    }
                ]))
            }),
        );

    tokio::spawn(async move {
        axum::serve(listener, app).await.unwrap();
    });

    format!("http://127.0.0.1:{}", port)
}

fn run_tui_dump(url: &str, tab: usize) -> Buffer {
    let output = Command::new(env!("CARGO_BIN_EXE_xavier-tui"))
        .env("XAVIER_TUI_DUMP", "1")
        .env("XAVIER_TUI_TAB", tab.to_string())
        .env("XAVIER_URL", url)
        .env("XAVIER_TOKEN", "test-token")
        .output()
        .expect("failed to run xavier-tui");

    if !output.status.success() {
        panic!(
            "xavier-tui failed with status {}: {}",
            output.status,
            String::from_utf8_lossy(&output.stderr)
        );
    }

    serde_json::from_slice(&output.stdout).expect("failed to parse TUI buffer JSON")
}

#[tokio::test]
async fn test_tui_screenshots() {
    let mock_url = start_mock_server().await;

    let screenshot_dir = Path::new("tests/e2e/screenshots");
    fs::create_dir_all(screenshot_dir).expect("failed to create screenshot directory");

    let tabs = [
        (0, "dashboard", "Dashboard"),
        (1, "explorer", "Memory Explorer"),
        (2, "logs", "Log Stream"),
    ];

    for (tab_idx, name, expected_text) in tabs {
        let buffer = run_tui_dump(&mock_url, tab_idx);

        // Verify content
        let mut found = false;
        for y in 0..buffer.area.height {
            let mut line = String::new();
            for x in 0..buffer.area.width {
                line.push_str(buffer[(x, y)].symbol());
            }
            if line.contains(expected_text) {
                found = true;
                break;
            }
        }
        assert!(
            found,
            "Could not find '{}' in TUI output for tab {}",
            expected_text, name
        );

        // Generate screenshot
        let screenshot_path = screenshot_dir.join(format!("{}.png", name));
        render_buffer_to_png(&buffer, &screenshot_path);
        assert!(screenshot_path.exists());
    }
}
